## 先把问题记下来

写作的起点可以很小。一个没想通的问题、一段刚刚跑通的代码，或者一本书里让人停下来的句子，都可以先成为一份草稿。

不必在第一遍就决定文章的全部结构。先写下目前能够确认的内容，再给不确定的地方留出标记。这样的记录容易继续，也容易在以后修订。

## 给记录一个清楚的结构

标题回答这篇文章在说什么，摘要交代为什么值得打开，正文则把背景、过程与结果分开。

- 背景：为什么开始关注这个问题。
- 过程：尝试过哪些办法。
- 结果：现在能够确认什么。
- 后续：哪些问题还没有答案。

结构不是为了让每一篇都长得一样，而是帮助读者少花一点时间寻找重点。生活随笔可以自由一些，技术笔记则更需要把前提写清楚。

### 别省略真正有用的细节

一个配置项适用于哪个环境，一张照片拍摄时的光线有什么不同，一本书为什么在此刻值得读，这些内容往往比一句结论更有价值。

